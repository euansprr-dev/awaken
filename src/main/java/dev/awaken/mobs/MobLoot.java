import net.minecraft.world.level.storage.loot.functions.LootItemFunction;
import net.minecraft.world.level.storage.loot.parameters.LootContextParams;
import net.minecraft.world.level.storage.loot.predicates.LootItemCondition;
import net.neoforged.bus.api.IEventBus;
import net.neoforged.neoforge.attachment.AttachmentType;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;
import net.neoforged.neoforge.registries.NeoForgeRegistries;
import org.jspecify.annotations.Nullable;

import java.util.Optional;
import java.util.function.Supplier;

/**
 * Drops. Loot tables (generated by tools/content/mobs_content.py) carry the themed drops, boss parts and essence
 * shards through {@code awaken:mob_level_count}, which scales a count by the dying creature's content level. Code adds
 * what a table can't know: the Lord Heart, Power Cores (with the per-player pity timer) and the boss counters.
 */
public final class MobLoot {
    private MobLoot() {}

    static final DeferredRegister<MapCodec<? extends LootItemFunction>> FUNCTIONS = DeferredRegister.create(Registries.LOOT_FUNCTION_TYPE, Awaken.MODID);
    public static final DeferredHolder<MapCodec<? extends LootItemFunction>, MapCodec<LevelCount>> LEVEL_COUNT = FUNCTIONS.register("mob_level_count", () -> LevelCount.MAP_CODEC);

    static final DeferredRegister<AttachmentType<?>> ATTACHMENTS = DeferredRegister.create(NeoForgeRegistries.ATTACHMENT_TYPES, Awaken.MODID);
    public static final Supplier<AttachmentType<BossRecord>> BOSS_RECORD = ATTACHMENTS.register("mobs_boss_record",
            () -> AttachmentType.builder(() -> BossRecord.EMPTY).serialize(BossRecord.MAP_CODEC).copyOnDeath().build());

    static void init(IEventBus modBus) {
        FUNCTIONS.register(modBus);
        ATTACHMENTS.register(modBus);
    }

    /** count = floor(base + perLevel * level + random), at most {@code max}; level is the creature's content level. */
    public static final class LevelCount extends LootItemConditionalFunction {
        public static final MapCodec<LevelCount> MAP_CODEC = RecordCodecBuilder.mapCodec(i -> commonFields(i).and(i.group(
                Codec.FLOAT.optionalFieldOf("base", 1.0F).forGetter(f -> f.base),
                Codec.FLOAT.optionalFieldOf("per_level", 0.0F).forGetter(f -> f.perLevel),
                Codec.INT.optionalFieldOf("max", 64).forGetter(f -> f.max)
        )).apply(i, LevelCount::new));

        final float base, perLevel;
        final int max;

        private LevelCount(Optional<Holder<LootItemCondition>> condition, float base, float perLevel, int max) {
            super(condition);
            this.base = base;
            this.perLevel = perLevel;
            this.max = max;
        }

        @Override
        public MapCodec<LevelCount> codec() {
            return MAP_CODEC;
        }

        @Override
        protected ItemStack run(ItemStack stack, LootContext context) {
            Entity e = context.getOptional(LootContextParams.THIS_ENTITY);
            int lv = e == null ? 0 : e.getData(CoreApi.MOB_ROLE.get()).contentLevel();
            stack.setCount(count(base, perLevel, max, lv, context.getRandom().nextFloat()));
            return stack;
        }
    }

    public static int count(float base, float perLevel, int max, int lv, float roll) {
        return Math.max(0, Math.min(max, (int) Math.floor(base + perLevel * lv + roll)));
    }

    /** The rank whose gates sit at this content level (E for anything below D's). */
    public static Rank rankFor(int lv) {
        Rank best = Rank.E;
        for (Rank r : Rank.values()) if (r.contentLevel <= lv) best = r;
        return best;
    }

    static @Nullable ServerPlayer killer(LivingEntity dead, DamageSource source) {
        if (source.getEntity() instanceof ServerPlayer sp) return sp;
        if (dead.getKillCredit() instanceof ServerPlayer sp) return sp;
        return null;
    }

    /** Chance a boss of this tier drops a Power Core without pity. */
    public static float coreChance(Tier tier) {
        return switch (tier) {
            case LORD -> 0.4F;
            case GUARDIAN -> 0.5F;
            case SOVEREIGN -> 0.75F;
            case FINAL -> 1.0F;
            case NIGHTMARE -> 0.15F;
            default -> 0.0F;
        };
    }

    /** Lord Heart and Power Core. Called while the boss drops its loot. */
    public static void bossDrops(ServerLevel level, AwakenBoss boss, DamageSource source) {
        MobDef d = boss.def();
        if (boss.isDecoy()) return;
        ServerPlayer sp = killer(boss, source);
        if (sp == null) return;
        if (d.tier == Tier.LORD) boss.spawnAtLocation(level, new ItemStack(CoreApi.LORD_HEART.get()));
        BossRecord rec = sp.getData(BOSS_RECORD.get());
        boolean pity = d.tier.countsAsBoss() && rec.pityDue();
        boolean roll = pity || boss.getRandom().nextFloat() < coreChance(d.tier);
        boolean got = false;
        if (roll) {
            ItemStack core = PowerCoreHooks.roll(rankFor(boss.contentLevel()), boss.getRandom());
            if (!core.isEmpty()) {
                boss.spawnAtLocation(level, core);
                got = true;
                Progression.markNewThing(sp, "power core from " + d.id);
            }
        }
        if (d.tier.countsAsBoss()) sp.setData(BOSS_RECORD.get(), rec.afterBoss(got));
        DirectorLog.log(sp, "mobs", d.id + " lv" + boss.contentLevel() + " core=" + got + (pity ? " (pity)" : "") + " since_core=" + sp.getData(BOSS_RECORD.get()).sinceCore());
    }

    /** Elites and Wardens sometimes carry a Power Core; more often when nothing new has happened for 20 minutes. */
    public static void eliteDrop(ServerLevel level, LivingEntity mob, MobRole role, DamageSource source) {
        float chance = switch (role.role()) {
            case ELITE -> 0.06F;
            case WARDEN -> 0.15F;
            default -> 0.0F;
        };
        if (chance <= 0) return;
        ServerPlayer sp = killer(mob, source);
        if (sp == null) return;
        if (Progression.minutesSinceNewThing(sp) >= 20) chance *= 1.5F;
        if (mob.getRandom().nextFloat() >= chance) return;
        ItemStack core = PowerCoreHooks.roll(rankFor(role.contentLevel()), mob.getRandom());
        if (core.isEmpty()) return;
        mob.spawnAtLocation(level, core);
        Progression.markNewThing(sp, "power core from an elite");
    }

    /** Counters, the trophy moment and Insight. Called once after a boss really dies. */
    public static void onBossKilled(ServerLevel level, AwakenBoss boss, DamageSource source) {
        MobDef d = boss.def();
        if (boss.isDecoy()) return;
        boss.playLevelSound(MobSounds.BOSS_DEFEATED.get(), 2.0F, 1.0F);
        ServerPlayer sp = killer(boss, source);
        if (sp == null || !d.tier.countsAsBoss()) return;
        Progression.count(sp, "awaken:bosses_killed", 1);
        if (sp.getMainHandItem().isEmpty()) Progression.count(sp, "awaken:bosses_killed_unarmed", 1);
        BossRecord rec = sp.getData(BOSS_RECORD.get());
        boolean first = !rec.hasKilled(d.bossId());
        String how = sp.getMainHandItem().isEmpty() ? " with bare hands" : "";
        if (first) {
            sp.setData(BOSS_RECORD.get(), rec.withKill(d.bossId()));
            Progression.markNewThing(sp, "trophy:" + d.bossId());
            Progression.bestMoment(sp, "First kill: " + d.name + how);
        } else {
            Progression.bestMoment(sp, "Felled " + d.name + how);
        }
        Signal.toast(sp, Component.literal(d.name + " falls.").withColor(d.glow));
    }
}
