package dev.awaken.powers.fx;

import dev.awaken.powers.PowerRegistry;
import dev.awaken.powers.PowerType;
import dev.awaken.powers.PowerType.Family;
import org.jspecify.annotations.Nullable;

import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Which full-body clip a cast pose plays when the Player Animation Library is installed (an optional client mod; the
 * client half is {@code powers.client.fx.PalCasts}). Every family has its own cast (wind-up, release,
 * follow-through), the release half of it for after a held wind-up, and a held wind-up loop with its let-go. A few
 * poses are what the power does to the body rather than its style, and look the same in every family: a dash plays
 * the Velocity burst, a hover the hover, a slam its wind-up and landing, a flurry the flurry. The clips are generated by
 * tools/art/specs/power_casts.py into {@code assets/awaken/player_animations/power_casts.json}.
 * <p>
 * Shared by both sides only so the GameTests can hold the table to the generated file; nothing here touches the
 * library.
 */
public final class CastClips {
    private CastClips() {}

    /** The clip file's namespace path, for the asset test. */
    public static final String FILE = "assets/awaken/player_animations/power_casts.json";

    private static final String[] SPECIAL = {"slam_wind", "slam_wind_end", "slam", "flurry", "hover", "hover_end"};

    /** The clip a pose plays: {@code afterHold} when it releases a held wind-up (the clip then starts at the strike). */
    public static @Nullable String clip(Family family, CastAnim kind, boolean afterHold) {
        String f = name(family);
        return switch (kind) {
            case NONE -> null;
            case DASH -> afterHold ? "cast_velocity_release" : "cast_velocity";
            case HOVER -> "hover";
            case SLAM_WIND -> "slam_wind";
            case SLAM -> "slam";
            case FLURRY -> "flurry";
            case PUNCH_WIND, CHARGE2, AIM_HOLD -> "hold_" + f;
            default -> afterHold ? "cast_" + f + "_release" : "cast_" + f;
        };
    }

    /** The clip that lets go of a held pose when no release follows it (eases back to the vanilla pose). */
    public static @Nullable String letGo(Family family, CastAnim held) {
        return switch (held) {
            case HOVER -> "hover_end";
            case SLAM_WIND -> "slam_wind_end";
            case PUNCH_WIND, CHARGE2, AIM_HOLD -> "hold_" + name(family) + "_end";
            default -> null;
        };
    }

    /** Every clip the table can name. */
    public static List<String> all() {
        List<String> out = new ArrayList<>();
        for (Family f : Family.values()) {
            String n = name(f);
            Collections.addAll(out, "cast_" + n, "cast_" + n + "_release", "hold_" + n, "hold_" + n + "_end");
        }
        Collections.addAll(out, SPECIAL);
        return out;
    }

    private static String name(Family f) {
        return f.name().toLowerCase(Locale.ROOT);
    }

    // ---- the caster's family from an FX event -----------------------------------------------------------------------

    /**
     * The family of the power behind an event. Events carry the power's style and pose, not the power: the pair (with
     * the ultimate flag) names the power's family for every designed effect; a pose only one family uses names it next;
     * the style decides the rest.
     */
    public static Family family(FxStyle style, CastAnim anim, boolean ultimate) {
        Family f = Index.EXACT.get(key(style, anim, ultimate));
        if (f == null) f = Index.BY_ANIM.get(anim);
        return f != null ? f : family(style);
    }

    public static Family family(FxEvent e) {
        return family(e.style(), e.anim(), e.has(FxEvent.ULT));
    }

    /** The family a style reads as, when nothing else says (variant styles: heat, charge, soul, frost...). */
    static Family family(FxStyle style) {
        return switch (style.plain()) {
            case KINETIC -> Family.KINETIC;
            case VELOCITY -> Family.VELOCITY;
            case FLIGHT, GRAVITY -> Family.FLIGHT;
            case SHADOW -> Family.SHADOW;
            case MIND -> Family.MIND;
            case ARCHITECT -> Family.ARCHITECT;
            case TECH -> Family.TECH;
            case SPIRIT, SOUL, FROST -> Family.SPIRIT;
            // plain() never returns an awakened style; they read as their plain one
            default -> Family.ENERGY;
        };
    }

    private static int key(FxStyle style, CastAnim anim, boolean ult) {
        return (style.ordinal() * 64 + anim.ordinal()) * 2 + (ult ? 1 : 0);
    }

    /** Built on first use from the FX table and the catalog (the holder makes it lazy and thread-safe). */
    private static final class Index {
        static final Map<Integer, Family> EXACT = new HashMap<>();
        static final Map<CastAnim, Family> BY_ANIM = new EnumMap<>(CastAnim.class);

        static {
            List<Integer> clash = new ArrayList<>();
            List<CastAnim> animClash = new ArrayList<>();
            for (PowerFxDefs.Def d : PowerFxDefs.ALL.values()) {
                PowerType t = PowerRegistry.get(d.power());
                if (t == null) continue;
                for (CastAnim a : new CastAnim[]{d.anim(), d.windAnim()}) {
                    if (a == null || a == CastAnim.NONE) continue;
                    int k = key(d.style(), a, d.ultimate());
                    Family before = EXACT.putIfAbsent(k, t.family);
                    if (before != null && before != t.family) clash.add(k);
                    Family b2 = BY_ANIM.putIfAbsent(a, t.family);
                    if (b2 != null && b2 != t.family) animClash.add(a);
                }
            }
            clash.forEach(EXACT::remove);
            animClash.forEach(BY_ANIM::remove);
        }
    }
}
