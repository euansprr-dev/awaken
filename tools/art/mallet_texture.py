#!/usr/bin/env python3
"""The Mallet's item texture (SPEC 52.1). Run from the repo root."""
from PIL import Image

ART = """
................
........##......
.......#aa#.....
......#aaib#....
......#aaIbc#...
.......#iIcc#...
........#Icdd#..
.......h#ccdd#..
......hH.#cd#...
.....hHn..##....
....hHn.........
...hHn..........
..hHn...........
.hHn............
.Hn.............
................
""".strip("\n").splitlines()
PALETTE = {
    "#": (43, 29, 20, 255), "a": (201, 160, 106, 255), "b": (169, 124, 74, 255), "c": (138, 95, 54, 255),
    "d": (107, 69, 38, 255), "i": (168, 174, 180, 255), "I": (110, 116, 121, 255),
    "h": (168, 129, 79, 255), "H": (125, 90, 53, 255), "n": (79, 54, 31, 255),
}
image = Image.new("RGBA", (16, 16))
for y, row in enumerate(ART):
    for x, ch in enumerate(row):
        if ch != ".":
            image.putpixel((x, y), PALETTE[ch])
image.save("src/main/resources/assets/awaken/textures/item/mallet.png")
