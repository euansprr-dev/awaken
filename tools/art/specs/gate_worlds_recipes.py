def rare_recipe(wid, w):
    return {
        "schema": 1,
        "theme": w["theme"],
        "name": w["name"],
        "line": w["line"],
        "tier": "rare",
        "rarity": w["rarity"],
        "kind": w.get("kind", "caves"),
        **({"tall": True} if w.get("tall") else {}),
        "roles": ["floor"],
        "params": w["params"],
        "biome": f"awaken:gate_world/{wid}",
        "moods": [dict({"id": mid, "name": name, "weight": weight, "biome": "" if i == 0 else f"awaken:gate_world/{wid}_{mid}"},
                       **({"life": life} if life else {})) for i, (mid, name, weight, life) in enumerate(w["moods"])],
        "blocks": w["blocks"],
        "hero": [],
        "life": w["life"],
        "sound": "awaken:gate.world." + w["sound"],
        "events": w["events"],
        "rule": w["rule"],
        "secrets": [{"id": sid, "name": name} for sid, name in w["secrets"]],
        "keepsake": w["keepsake"][0],
        "keepsake_name": w["keepsake"][1],
        "keepsake_from": w["keepsake"][2],
    }


def recipe(theme, t, wid, w):
    secret = w["tier"] == "secret"
    secrets = []
    if not secret:
        secrets.append({"id": t["touch"][0], "name": t["touch"][1]})
    for sid, name in w["secrets"]:
        secrets.append({"id": sid, "name": name})
    if w.get("lead"):
        secrets.append({"id": t["lead"][0], "name": t["lead"][1], "leads_to": f"awaken:{theme}/{t['secret_world']}"})
    blocks = dict(t["blocks"])
    if "fluid" in w:
        blocks["fluid"] = w["fluid"]
    out = {
        "schema": 1,
        "theme": theme,
        "name": w["name"],
        "line": w["line"],
        "tier": w["tier"],
        "rarity": w["rarity"],
        "kind": w.get("kind", "caves"),
        "roles": ["floor"] if secret else ["floor", "boss"],
        "params": w["params"],
        "biome": f"awaken:gate_world/{wid}",
        "moods": [] if secret else [
            dict({"id": mid, "name": name, "weight": weight, "biome": "" if i == 0 else f"awaken:gate_world/{wid}_{mid}"},
                 **({"life": life} if life else {}))
            for i, (mid, name, weight, life) in enumerate(t["moods"])],
        "blocks": blocks,
        "hero": w["hero"],
        "life": w.get("life", t["life"]),
        "sound": "awaken:gate.world." + w["sound"],
        "events": w["events"],
        "rule": t["rule"],
        "secrets": secrets,
        "keepsake": w["keepsake"][0],
        "keepsake_name": w["keepsake"][1],
        "keepsake_from": w["keepsake"][2],
    }
    if w.get("tall"):
        out["tall"] = True
    if w.get("signature"):
        out["signature"] = w["signature"]
    return out


def main():
    n = 0
    for theme, t in THEMES.items():
        os.makedirs(os.path.join(ROOT, theme), exist_ok=True)
        for wid, w in t["worlds"].items():
            with open(os.path.join(ROOT, theme, wid + ".json"), "w") as f:
                json.dump(recipe(theme, t, wid, w), f, indent=2)
                f.write("\n")
            n += 1
    os.makedirs(os.path.join(ROOT, "rare"), exist_ok=True)
    for wid, w in RARE.items():
        with open(os.path.join(ROOT, "rare", wid + ".json"), "w") as f:
            json.dump(rare_recipe(wid, w), f, indent=2)
            f.write("\n")
        n += 1
    print(n, "recipes")


if __name__ == "__main__":
    main()
