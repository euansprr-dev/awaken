BG_DAY = (112, 132, 108, 255)
BG_NIGHT = (8, 10, 22, 255)


def _old_render(hid, before_dir, px):
    """The old body, if its texture was saved to before_dir."""
    from PIL import Image
    if not before_dir or hid not in OLD:
        return None
    model, vtex, tint, scale = OLD[hid]
    skin_p = os.path.join(before_dir, hid + ".png")
    if not os.path.exists(skin_p):
        return None
    import fauna as F1
    import fauna2 as F2
    models = dict(F1.MODELS)
    models.update(F2.MODELS)
    _, tree = models[model]()
    skin = Image.open(skin_p).convert("RGBA")
    if vtex:
        vb = Image.open(os.path.join(F1.VANILLA_TEX, vtex + ".png")).convert("RGBA").resize(skin.size, Image.NEAREST)
        t = R.hexc(tint)
        vpx = vb.load()
        for y in range(vb.height):
            for x in range(vb.width):
                r_, g_, b_, a_ = vpx[x, y]
                vpx[x, y] = (r_ * t[0] // 255, g_ * t[1] // 255, b_ * t[2] // 255, a_)
        mask = skin.split()[3].point(lambda a: 255 if a >= 128 else 0)
        base = Image.alpha_composite(vb, Image.composite(skin, Image.new("RGBA", skin.size), mask))
    else:
        base = skin
    _add_scale(tree, scale)
    return R.render(tree, base, yaw=60, pitch=8, px=px)


def _add_scale(tree, scale):
    """Entity scale around the feet (ground at y = 24)."""
    tree["scale"] = (scale, scale, scale)
    tree["pivot"] = (0, 24 - 24 * scale, 0)


def preview(outdir, only=None, before=None):
    from PIL import Image, ImageDraw
    os.makedirs(outdir, exist_ok=True)
    made = []
    for hid, rig, painter in rigs(only):
        skin, glow = paint(rig, painter)
        sk, gl = skin.image(), glow.image()
        lit = Image.alpha_composite(sk, gl)
        rest = rig.tree()
        cell = (300, 260)
        views = [R.render(rest, lit, yaw=35, pitch=18, size=cell), R.render(rest, lit, yaw=100, pitch=8, size=cell),
                 R.render(rest, lit, yaw=-145, pitch=30, size=cell), R.render(rest, sk, yaw=35, pitch=18, size=cell, night=gl)]
        row1 = Image.new("RGBA", (cell[0] * 4, cell[1]), BG_DAY)
        for i, im in enumerate(views):
            bg = Image.new("RGBA", cell, BG_NIGHT if i == 3 else BG_DAY)
            bg.alpha_composite(im, (0, 0))
            row1.paste(bg, (i * cell[0], 0))
        # size: player, old body, new body on one ground line, same pixels per model pixel
        unit = 4.0
        scale = SCALE.get(hid, 1.0)
        tnew = rig.tree(rig.sample([("idle", 0.4, 1.0)]))
        _add_scale(tnew, scale)
        new_im = R.render(tnew, lit, yaw=60, pitch=8, px=unit)
        old_im = _old_render(hid, before, unit)
        pl = R.render(R.player_tree(), R.steve(), yaw=60, pitch=8, px=unit)
        items = [("player", pl)] + ([("before", old_im)] if old_im is not None else []) + [("after", new_im)]
        W2 = sum(im.width for _, im in items) + 40 * len(items) + 20
        H2 = max(im.height for _, im in items) + 40
        row2 = Image.new("RGBA", (max(W2, cell[0] * 4), H2), (150, 170, 150, 255))
        d2 = ImageDraw.Draw(row2)
        x, ground = 20, H2 - 24
        for name, im in items:
            row2.alpha_composite(im, (x, ground - im.height + 8))
            d2.text((x, ground + 6), name, fill=(20, 24, 30, 255))
            x += im.width + 40
        d2.line((0, ground, row2.width, ground), fill=(60, 80, 60, 255))
        # key poses
        poses = pose_list(rig)
        trees = [rig.tree(rig.sample(layers)) for _, layers in poses]
        yaw, pitch = 55, 12
        b = R.bounds_of(trees, yaw, pitch)
        pc = (240, 220)
        px = min((pc[0] - 16) / (b[1] - b[0]), (pc[1] - 24) / (b[3] - b[2]))
        row3 = Image.new("RGBA", (max(pc[0] * len(poses), cell[0] * 4), pc[1] + 16), (40, 44, 54, 255))
        d3 = ImageDraw.Draw(row3)
        for k, ((label, _), t) in enumerate(zip(poses, trees)):
            im = R.render(t, lit, yaw=yaw, pitch=pitch, px=px, bounds=b,
                          origin=(pc[0], pc[1], (pc[0] - (b[1] - b[0]) * px) / 2 - b[0] * px, pc[1] - 8 - b[3] * px))
            bg = Image.new("RGBA", pc, BG_DAY)
            bg.alpha_composite(im)
            row3.paste(bg, (k * pc[0], 0))
            d3.text((k * pc[0] + 4, pc[1] + 2), label, fill=(220, 225, 235, 255))
        Wt = max(row1.width, row2.width, row3.width)
        sheet = Image.new("RGBA", (Wt, row1.height + row2.height + row3.height + 40), (24, 26, 34, 255))
        sd = ImageDraw.Draw(sheet)
        sheet.paste(row1, (0, 0))
        sheet.paste(row2, (0, row1.height + 20))
        sheet.paste(row3, (0, row1.height + row2.height + 40))
        sd.text((6, row1.height + 4), f"{hid}: {len(rig.bones)} bones, {len(rig.cubes)} cubes, tex {rig.tex[0]}x{rig.tex[1]} "
                                      f"(used {rig.used} rows), {len(rig.clips)} clips", fill=(220, 225, 235, 255))
        path = os.path.join(outdir, f"hero_{hid}.png")
        sheet.save(path)
        sk.resize((sk.width * 4, sk.height * 4), Image.NEAREST).save(os.path.join(outdir, f"hero_{hid}_tex.png"))
        made.append(path)
    print("\n".join(made))


def pose_list(rig):
    """(label, layers) for the pose strip: rest, walk, run, the first move's wind-up end and strike, roar, hurt, death."""
    out = [("idle", [("idle", 0.8, 1.0)])]
    if "walk" in rig.clips:
        out.append(("walk", [("idle", 0.8, 0.4), ("walk", rig.clips["walk"].length * 0.25, 1.0)]))
    if "run" in rig.clips:
        out.append(("run", [("run", rig.clips["run"].length * 0.3, 1.0)]))
    if "fly" in rig.clips:
        out.append(("fly", [("fly", rig.clips["fly"].length * 0.3, 1.0)]))
    if "air" in rig.clips:
        out.append(("glide", [("air", rig.clips["air"].length * 0.3, 1.0)]))
    sig = None
    for ability, mv in rig.moves.items():
        if mv + "_windup" in rig.clips:
            sig = mv
            break
    if sig:
        wl = rig.clips[sig + "_windup"].length
        out.append((sig + " wind-up", [("idle", 0.8, 1.0), (sig + "_windup", wl, 1.0)]))
        sl = rig.clips[sig + "_strike"].length
        out.append((sig + " strike", [(sig + "_strike", sl * 0.25, 1.0)]))
    if "roar" in rig.clips:
        out.append(("roar", [("roar", rig.clips["roar"].length * 0.55, 1.0)]))
    if "hurt" in rig.clips:
        out.append(("hurt", [("idle", 0.8, 1.0), ("hurt", 0.07, 1.0)]))
    if "death" in rig.clips:
        out.append(("death", [("death", rig.clips["death"].length, 1.0)]))
    return out


def poses_sheet(outdir, hid, labels_times):
    """Ad-hoc pose strip: [(label, [(clip, t, w)])] for one hero (used while authoring)."""
    from PIL import Image, ImageDraw
    rig = H.HEROES[hid][0]()
    skin, glow = paint(rig, H.HEROES[hid][1])
    lit = Image.alpha_composite(skin.image(), glow.image())
    trees = [rig.tree(rig.sample(l)) for _, l in labels_times]
    yaw, pitch = 55, 12
    b = R.bounds_of(trees, yaw, pitch)
    pc = (240, 220)
    px = min((pc[0] - 16) / (b[1] - b[0]), (pc[1] - 24) / (b[3] - b[2]))
    row = Image.new("RGBA", (pc[0] * len(trees), pc[1] + 16), (40, 44, 54, 255))
    d = ImageDraw.Draw(row)
    for k, ((label, _), t) in enumerate(zip(labels_times, trees)):
        im = R.render(t, lit, yaw=yaw, pitch=pitch, px=px, bounds=b,
                      origin=(pc[0], pc[1], (pc[0] - (b[1] - b[0]) * px) / 2 - b[0] * px, pc[1] - 8 - b[3] * px))
        bg = Image.new("RGBA", pc, BG_DAY)
        bg.alpha_composite(im)
        row.paste(bg, (k * pc[0], 0))
        d.text((k * pc[0] + 4, pc[1] + 2), label, fill=(220, 225, 235, 255))
    path = os.path.join(outdir, f"poses_{hid}.png")
    row.save(path)
    print(path)


