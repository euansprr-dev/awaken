# The new bodies' entity scale (the bestiary's .scale): heroes are modelled at true size.
SCALE = {"briar_sow": 1.15, "dune_wyrm": 1.4, "old_antler": 1.2, "mire_mother": 1.2, "plumed_coil": 1.5, "weaver_queen": 1.3, "empress_moth": 1.8, "stonehorn": 1.6, "mycelord": 1.5, "hollow_owl": 1.2, "bogwick": 1.0}


def rigs(only=None):
    out = []
    for hid, (design, painter) in H.HEROES.items():
        if only and hid not in only:
            continue
        rig = design()
        out.append((hid, rig, painter))
    return out


def paint(rig, painter):
    P = R.Painter(rig, "heroes|" + rig.id)
    return painter(rig, P)


def java(all_rigs):
    chunks = []
    for hid, rig, _ in all_rigs:
        problems = rig.check()
        if problems:
            raise SystemExit("\n".join(problems))
        lines = rig.java_lines()
        block, size = [], 0
        parts = []
        for ln in lines:
            if size + len(ln) > 24000 and block:
                parts.append(block)
                block, size = [], 0
            block.append(ln)
            size += len(ln) + 1
        if block:
            parts.append(block)
        chunks.append((hid, parts))
    src = ["package dev.awaken.mobs.client.anim;", "",
           "import java.util.List;", "",
           "/**",
           " * GENERATED by tools/art/specs/heroes.py from fauna_heroes.py: do not edit by hand. Plain data (no Minecraft",
           " * classes): the hero rigs' bones, cubes, look bones, ability-to-move map and keyframe clips, parsed by",
           " * {@link HeroRig#parse}. Texture layouts match textures/entity/mobs/{id}.png.",
           " */",
           "public final class HeroData {",
           "    private HeroData() {}", "",
           "    /** Every rig's source text, in order. */",
           "    public static final List<String[]> SOURCES = List.<String[]>of("]
    for k, (hid, parts) in enumerate(chunks):
        src.append(f"            // {hid}")
        src.append("            new String[] {")
        for pi, block in enumerate(parts):
            src.append('                """')
            for ln in block:
                src.append("                " + ln)
            src.append('                """' + ("," if pi < len(parts) - 1 else ""))
        src.append("            }" + ("," if k < len(chunks) - 1 else ""))
    src.append("    );")
    src.append("}")
    os.makedirs(os.path.dirname(JAVA_OUT), exist_ok=True)
    with open(JAVA_OUT, "w") as f:
        f.write("\n".join(src) + "\n")
    return JAVA_OUT


def build(out=None):
    all_rigs = rigs()
    for hid, rig, painter in all_rigs:
        skin, glow = paint(rig, painter)
        if out is not None:
            out.entity("mobs/" + hid, skin)
            out.entity("mobs/" + hid + "_glow", glow)
        else:
            os.makedirs(TEX_DIR, exist_ok=True)
            skin.image().save(os.path.join(TEX_DIR, hid + ".png"))
            glow.image().save(os.path.join(TEX_DIR, hid + "_glow.png"))
    path = java(all_rigs)
    print(f"heroes: {len(all_rigs)} rigs -> {os.path.relpath(path, ROOT)}")


