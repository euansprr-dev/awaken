"""Hero bodies for the nine named beasts (plus the Hollow Owl and the Bogwick): textures, Java rig data, previews.

    python3 tools/art/build_all.py heroes          textures (skin + glow) and src/.../mobs/client/anim/HeroData.java
    python3 tools/art/specs/heroes.py build        the same
    python3 tools/art/specs/heroes.py preview DIR [ids...] [--before OLD_TEXTURE_DIR]
                                                   per hero: three day views and a night view; old body beside the
                                                   new one with a player for scale; key poses (idle, walk, run, the
                                                   signature wind-up and strike, roar, hurt, death)

Designs live in fauna_heroes.py (geometry, paint, keyframes), the toolkit in fauna_rig.py / fauna_anim.py. The Java
side reads HeroData.java (plain data, no Minecraft classes) through HeroRig.java; HeroModel bakes it into a
LayerDefinition and vanilla AnimationDefinitions, so the preview poses are the game's poses.
"""
