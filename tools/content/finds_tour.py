#!/usr/bin/env python3
"""Writes the finds' gallery tour (tools/autopilot/finds-gallery.txt) from the kinds in src/main/java/dev/awaken/finds/sets.

Every kind is stood on its own pad in the sky with `/awaken finds place` and photographed from the front (and from the
side when it is long), in six tours of three sets (finds-gallery-a to -f), so a runner that loses its GPU costs one part. finds-world visits the twelve
finds nearest the spawn that the world itself made, and finds-journal opens the Journal's Places shelf. Run it again
whenever a kind is added or its reach changes:  python3 tools/content/finds_tour.py
"""
import math, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SETS = ["CAIRNS", "STILLED", "LAMPS", "RINGING", "MACHINES", "GODS", "WISPS", "BURIED", "HUNG", "DRY", "MARKS", "RUNS", "HIGH",
        "WEATHER", "MENDED", "SURVEY", "SEALED", "BEASTS"]
kinds = []
for f in sorted((ROOT / "src/main/java/dev/awaken/finds/sets").glob("*.java")):
    text = f.read_text()
    for m in re.finditer(r'Kind\.of\(FSet\.(\w+), (\d+), "(\w+)", "([^"]+)"\)(.*?)\.add\(\);', text, re.S):
        reach = re.search(r"\.reach\((\d+)\)", m.group(5))
        kinds.append((SETS.index(m.group(1)), int(m.group(2)), m.group(3), int(reach.group(1)) if reach else 8))
kinds.sort()
assert len(kinds) == 144, len(kinds)

def head(world):
    """The standing start of a tour: the opening skipped (or its camera ride owns the first minute), awake, a starter power picked."""
    return ["# ci knobs: RD=10", f"world {world} creative 4242", "waitworld", "camera first", "cmd gamerule send_command_feedback false",
            "cmd weather clear 100000", "cmd gamerule advance_weather false", "cmd gamerule spawn_mobs false", "wait 40", "cmd awaken opening skip", "wait 160", "screen close",
            "cmd awaken admin awaken", "wait 200", "screen close", "cmd awaken powers starter 1", "wait 20", "cmd time set 6000", "cmd gamerule advance_time false"]


Y = 200


def stand(x, y, z, yaw, pitch):
    """The camera stands on an unseen block, so it holds still however long the runner takes to draw the land."""
    return [f"cmd setblock {x} {y - 1} {z} minecraft:barrier", f"cmd tp @s {x} {y} {z} {yaw} {pitch:.0f}"]


def gallery(name, part, note):
    out = [f"# The finds' gallery, {note}: every kind on its own pad in the sky, front on (and from the side when it's long).",
           "# GENERATED by tools/content/finds_tour.py. Look for: anything floating, overlapping or cut off; a third or more of each",
           "# not plain cubes; the ground changing round it."] + head("findsgallery") + ["cmd gamerule awaken:fauna_spawning false", "hud off", "opt fov 45"]
    shots = 0
    for i, (si, n, kid, reach) in enumerate(kinds):
        if not part(si):
            continue
        if shots == 0:  # the first pad is a long way from the spawn: be there, on something, before anything is stood
            out += [f"cmd tp @s {1000 + i * 130} 260 -40", "wait 100", f"cmd setblock {1000 + i * 130} 259 -40 minecraft:barrier",
                    f"cmd tp @s {1000 + i * 130} 260 -40", "wait 100"]
        x = 1000 + i * 130
        # a 45 degree lens sees about one and a half times its distance across: stand so the whole reach just fits
        dist = min(max(6, round(reach * 0.9) + 3), 16)
        h = round(2 + dist * 0.45)
        pitch = math.degrees(math.atan2(h - 2, dist))
        out += [f"cmd tp @s {x} {Y + h + 2} {-dist} 0 {pitch:.0f}", "wait 12",
                f"cmd execute positioned {x} {Y} 0 rotated 0 0 run awaken finds place {kid}"]
        out += stand(x, Y + h, -dist, 0, pitch) + ["wait 30", f"shot f{si + 1:02d}_{n}_{kid}"]
        shots += 1
        if reach > 14:
            side = round(reach * 1.2) + 4
            hs = round(side * 0.45)
            out += stand(x + side, Y + hs, 0, 90, math.degrees(math.atan2(hs - 2, side))) + ["wait 15", f"shot f{si + 1:02d}_{n}_{kid}_side"]
            shots += 1
    out += ["info", "quit"]
    (ROOT / f"tools/autopilot/{name}.txt").write_text("\n".join(out) + "\n")
    return shots


counts = [gallery("finds-gallery-" + "abcdef"[p], lambda si, p=p: si // 3 == p, f"sets {p * 3 + 1} to {p * 3 + 3}") for p in range(6)]
world = ["# The twelve finds nearest the spawn, as the world itself made them: do they sit in the land, and is the land between them left alone?",
         "# GENERATED by tools/content/finds_tour.py."] + head("findsworld") + ["hud off"]
for n in range(12):
    world += ["cmd time set 6000", f"cmd awaken finds visit {n}", "wait 100", f"shot world_{n:02d}"]
world += ["info", "quit"]
(ROOT / "tools/autopilot/finds-world.txt").write_text("\n".join(world) + "\n")
print("finds_tour: wrote", len(kinds), "kinds;", counts, "gallery shots and 12 of the world")

# The Journal's Places shelf with nothing found, with one set and a few others filed, and scrolled to the end.
journal = ["# The finds in the Journal: the Places shelf empty, part filled, and at its far end. GENERATED by tools/content/finds_tour.py."] \
    + head("findsjournal") + [
        "screen journal", "journal places", "wait 40", "shotnow journal_places_empty",
        "screen close", "cmd awaken finds grant cairns", "cmd awaken finds grant cold_lamps", "cmd awaken finds grant dry_basin",
        "cmd awaken finds grant gourd_tree", "cmd awaken finds grant sleeping_hill", "wait 20",
        "screen journal", "journal places", "wait 40", "shotnow journal_places_some", "scroll -6", "wait 10", "shotnow journal_places_some_2",
        "scroll -40", "wait 10", "shotnow journal_places_end", "screen close",
        "screen tasks", "wait 40", "shotnow tasks_with_finds", "screen close", "quit"]
(ROOT / "tools/autopilot/finds-journal.txt").write_text("\n".join(journal) + "\n")
