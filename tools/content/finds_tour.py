#!/usr/bin/env python3
"""Writes the places' look tours (tools/autopilot/places-a.txt to -f.txt, places-journal.txt) from the place files in
src/main/java/dev/awaken/finds/sets.

Each tour goes to three places where the world itself put them (`/awaken finds view <id> <camera>`) and takes five pictures
of each: from afar, from above, at the door, inside, and the door again at dusk. Six tours so they run side by side on
GitHub's runners and a runner that loses its GPU costs one part. Run it again when a place is added:
    python3 tools/content/finds_tour.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
places = []
for f in sorted((ROOT / "src/main/java/dev/awaken/finds/sets").glob("Places*.java")):
    for m in re.finditer(r'Kind\.of\(FSet\.PLACES, (\d+), "(\w+)", "([^"]+)"\)', f.read_text()):
        places.append((int(m.group(1)), m.group(2), m.group(3)))
places.sort()
assert len(places) == 30, len(places)


def head(world):
    """The standing start of a tour: the opening skipped (or its camera ride owns the first minute), awake, a starter power picked."""
    return ["# ci knobs: RD=12", f"world {world} creative 4242", "waitworld", "camera first", "cmd gamerule send_command_feedback false",
            "cmd weather clear 100000", "cmd gamerule advance_weather false", "cmd gamerule spawn_mobs false", "wait 40", "cmd awaken opening skip",
            "wait 160", "screen close", "cmd awaken admin awaken", "wait 200", "screen close", "cmd awaken powers starter 1", "wait 20",
            "cmd time set 6000", "cmd gamerule advance_time false"]


VIEWS = ["afar", "above", "door", "inside"]
for part in range(10):
    out = [f"# Places {part * 3 + 1} to {part * 3 + 3}, where the world put them: from afar, from above, at the door, inside, and the door at dusk.",
           "# GENERATED by tools/content/finds_tour.py. Look for: does it stand out from a distance, does it sit in its land, can you",
           "# see the way in, is the inside lit and furnished, is its air (fog, motes) there."] + head("places") + ["hud off"]
    for n, pid, name in places[part * 3:part * 3 + 3]:
        out += ["cmd time set 6000"]
        for v, label in enumerate(VIEWS):
            if v == 0:  # the first move waits for its land (a passage); the second view is then at once, in case the first came late
                out += [f"cmd awaken finds view {pid} 0", "wait 240", "waitpassage", "wait 80", f"cmd awaken finds view {pid} 0", "wait 80", "waitpassage", "wait 40"]
            out += [f"cmd awaken finds view {pid} {v}", "wait 60" if v == 0 else "wait 50", f"shot p{n:02d}_{pid}_{v}_{label}"]
        out += ["cmd time set 13000", f"cmd awaken finds view {pid} 2", "wait 50", f"shot p{n:02d}_{pid}_4_dusk"]
    out += ["info", "quit"]
    (ROOT / f"tools/autopilot/places-{'abcdefghij'[part]}.txt").write_text("\n".join(out) + "\n")

journal = ["# The places in the Journal: the Places shelf empty, part filled, and the Tasks page. GENERATED by tools/content/finds_tour.py."] \
    + head("placesjournal") + [
        "screen journal", "journal places", "wait 40", "shotnow journal_places_empty",
        "screen close", "cmd awaken finds grant charcoal_clearing", "cmd awaken finds grant drowned_chapel", "cmd awaken finds grant glowworm_cave",
        "cmd awaken finds grant hanging_village", "cmd awaken finds grant spore_cathedral", "wait 20",
        "screen journal", "journal places", "wait 40", "shotnow journal_places_some", "scroll -8", "wait 10", "shotnow journal_places_end", "screen close", "quit"]
(ROOT / "tools/autopilot/places-journal.txt").write_text("\n".join(journal) + "\n")
print("finds_tour: wrote ten tours of", len(places), "places, 150 shots, and the journal tour")
